let language = 'ko';
const textBindings = new WeakMap(), textNodes = new WeakMap(), attributeBindings = new WeakMap();
export const locale = () => language === 'en' ? 'en-US' : 'ko-KR';
const render = value => typeof value === 'function' ? value() : String(value ?? '');
export function t(key, params = {}, lang = language) {
  const template = String((lang === 'en' ? (english[key] ?? key) : key) ?? '');
  return template.replace(/\{(\w+)\}/g, (original, name) => Object.hasOwn(params, name) ? render(params[name]) : original);
}
export const m = (key, params = {}) => () => t(key, params);
export const join = (...parts) => () => parts.map(render).join('');
export const dateText = value => () => new Date(value).toLocaleString(locale(), {month:'short',day:'numeric',hour:'2-digit',minute:'2-digit'});

export function setText(element, value) {
  let text = textNodes.get(element);
  if (!text || text.parentNode !== element) {
    text = document.createTextNode(''); element.replaceChildren(text); textNodes.set(element, text);
  }
  text.nodeValue = render(value);
  if (typeof value === 'function') textBindings.set(text, value); else textBindings.delete(text);
}
export function attribute(element, name, value) {
  element.setAttribute(name, render(value));
  const bindings = attributeBindings.get(element) || {};
  if (typeof value === 'function') bindings[name] = value; else delete bindings[name];
  attributeBindings.set(element, bindings);
  element.dataset.uiAttributes = '';
}
export function setLanguage(value, persist = true) {
  language = value === 'en' ? 'en' : 'ko';
  if (persist) { try { localStorage.setItem('simasset-language', language); } catch {} }
  document.documentElement.lang = language;
  const select = document.getElementById('language'); if (select) select.value = language;
  const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) { const fn = textBindings.get(walker.currentNode); if (fn) walker.currentNode.nodeValue = fn(); }
  document.querySelectorAll('[data-ui-attributes]').forEach(element => {
    Object.entries(attributeBindings.get(element) || {}).forEach(([key, fn]) => element.setAttribute(key, fn()));
  });
  document.querySelectorAll('[data-theme-link]').forEach(link => {
    const url = new URL(link.href);
    url.pathname = '/d/simasset-local-review' + (language === 'en' ? '-en' : '');
    link.href = url.href;
  });
  const url = new URL(location.href); url.searchParams.set('lang', language); history.replaceState(null, '', url);
  window.dispatchEvent(new Event('simasset-language-change'));
}
export function initializeLanguage() {
  // This scan runs once, before any user content is rendered. Dynamic UI opts in via m().
  const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const text = walker.currentNode, key = text.nodeValue.trim();
    if (Object.hasOwn(english, key)) {
      const before = text.nodeValue.match(/^\s*/)[0], after = text.nodeValue.match(/\s*$/)[0];
      textBindings.set(text, () => before + t(key) + after);
    }
  }
  document.querySelectorAll('[aria-label],[placeholder],[title]').forEach(element => {
    for (const name of ['aria-label','placeholder','title']) {
      const key = element.getAttribute(name); if (Object.hasOwn(english, key)) attribute(element, name, m(key));
    }
  });
  let saved = 'ko'; try { saved = localStorage.getItem('simasset-language') || 'ko'; } catch {}
  const requested = new URLSearchParams(location.search).get('lang');
  setLanguage(['ko','en'].includes(requested) ? requested : saved);
  document.getElementById('language').addEventListener('change', event => setLanguage(event.target.value));
  window.addEventListener('storage', event => {
    if (event.key === 'simasset-language' || event.key === null) setLanguage(event.newValue, false);
  });
}
